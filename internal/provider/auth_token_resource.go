const (
	authTokenKind       = "Dash0AuthToken"
	authTokenAPIVersion = "dash0.com/v1alpha1"
	authTokenIDLabel    = "dash0.com/id"
	authTokenOriginKey  = "dash0.com/origin"
)

// authTokenServerDefaultedFields are ignored only when the user did not set
// them: the server always returns them, with defaults for omitted values.
var authTokenServerDefaultedFields = []string{
	"spec.ingestion",
	"spec.ingestion.defaultDataset",
	"spec.scope",
	"spec.scope.datasets",
	"spec.scope.datasets.restriction",
	"spec.scope.datasets.slugs",
	"spec.scope.signals",
	"spec.scope.signals.restriction",
	"spec.scope.signals.types",
}

// Ensure the implementation satisfies the expected interfaces.
var (
	_ resource.Resource                   = &AuthTokenResource{}
	_ resource.ResourceWithConfigure      = &AuthTokenResource{}
	_ resource.ResourceWithImportState    = &AuthTokenResource{}
	_ resource.ResourceWithValidateConfig = &AuthTokenResource{}
)

// NewAuthTokenResource is a helper function to simplify the provider implementation.
func NewAuthTokenResource() resource.Resource {
	return &AuthTokenResource{}
}

// AuthTokenResource is the resource implementation.
type AuthTokenResource struct {
	client client.Client
}

// authTokenModel is the Terraform state model for an auth token resource.
type authTokenModel struct {
	Origin        types.String `tfsdk:"origin"`
	ID            types.String `tfsdk:"id"`
	Token         types.String `tfsdk:"token"`
	AuthTokenYaml types.String `tfsdk:"auth_token_yaml"`
}

// Configure adds the provider configured client to the resource.
func (r *AuthTokenResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}

	data, ok := req.ProviderData.(resourceProviderData)
	if !ok {
		resp.Diagnostics.AddError(
			"Unexpected Data Source Configure Type",
			fmt.Sprintf("Expected provider.resourceProviderData, got: %T. Please report this issue to the provider developers.", req.ProviderData),
		)
		return
	}

	r.client = data.client
}

func (r *AuthTokenResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_auth_token"
}

