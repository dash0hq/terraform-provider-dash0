// ValidateConfig checks auth_token_yaml at plan time: syntax, kind and secret.
func (r *AuthTokenResource) ValidateConfig(ctx context.Context, req resource.ValidateConfigRequest, resp *resource.ValidateConfigResponse) {
	var yamlAttr types.String
	resp.Diagnostics.Append(req.Config.GetAttribute(ctx, path.Root("auth_token_yaml"), &yamlAttr)...)
	if resp.Diagnostics.HasError() || yamlAttr.IsNull() || yamlAttr.IsUnknown() {
		return
	}

	var parsed map[string]interface{}
	if err := yaml.Unmarshal([]byte(yamlAttr.ValueString()), &parsed); err != nil {
		resp.Diagnostics.AddAttributeError(path.Root("auth_token_yaml"), "Invalid YAML in auth_token_yaml",
			fmt.Sprintf("auth_token_yaml is not valid YAML: %s", err))
		return
	}
	if v, _ := parsed["apiVersion"].(string); v != authTokenAPIVersion {
		resp.Diagnostics.AddAttributeError(path.Root("auth_token_yaml"), "auth_token_yaml is missing or has the wrong apiVersion",
			fmt.Sprintf("auth_token_yaml must declare `apiVersion: %s`; got %q.", authTokenAPIVersion, v))
		return
	}
	if kind, _ := parsed["kind"].(string); kind != authTokenKind {
		resp.Diagnostics.AddAttributeError(path.Root("auth_token_yaml"), "auth_token_yaml is missing or has the wrong kind",
			fmt.Sprintf("auth_token_yaml must declare `kind: %s`; got %q.", authTokenKind, kind))
		return
	}
	if spec, ok := parsed["spec"].(map[string]interface{}); ok {
		if _, set := spec["token"]; set {
			resp.Diagnostics.AddAttributeError(path.Root("auth_token_yaml"), "spec.token must not be set",
				"Dash0 generates the secret and it cannot change. Remove spec.token and read the secret from the `token` attribute.")
		}
	}
}

func (r *AuthTokenResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var model authTokenModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &model)...)
	if resp.Diagnostics.HasError() {
		return
	}

	body, err := converter.ConvertYAMLToJSON(model.AuthTokenYaml.ValueString())
	if err != nil {
		resp.Diagnostics.AddError("Conversion Error", fmt.Sprintf("Unable to convert auth token YAML to JSON: %s", err))
		return
	}

	model.Origin = types.StringValue("tf_" + uuid.New().String())

	id, token, err := r.client.CreateAuthToken(ctx, model.Origin.ValueString(), body)
	if err != nil {
		resp.Diagnostics.AddError("Client Error", fmt.Sprintf("Unable to create auth token, got error: %s", err))
		return
	}
	model.ID = types.StringValue(id)
	model.Token = types.StringValue(token)

	tflog.Trace(ctx, "created an auth token resource")
	resp.Diagnostics.Append(resp.State.Set(ctx, model)...)
}

func (r *AuthTokenResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state authTokenModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	apiResponseJSON, token, err := r.client.GetAuthToken(ctx, state.ID.ValueString())
	if removedOutOfBand(ctx, resp, "Auth token", state.ID.ValueString(), apiResponseJSON, err) {
		return
	}
	if err != nil {
		resp.Diagnostics.AddError("Client Error", fmt.Sprintf("Unable to read auth token, got error: %s", err))
		return
	}

	tflog.Trace(ctx, "read an auth token resource")

	// The API returns the secret only when it creates the token: keep the one in state.
	if token != "" {
		state.Token = types.StringValue(token)
	}

	if stateYAML := state.AuthTokenYaml.ValueString(); stateYAML != "" {
		ignored := converter.FieldsAbsentFromYAML(stateYAML, authTokenServerDefaultedFields)
		equivalent, err := converter.ResourceYAMLEquivalent(stateYAML, apiResponseJSON, ignored, nil)
		if err != nil {
			resp.Diagnostics.AddError(
				"Auth Token Comparison Error",
				fmt.Sprintf("Failed to compare auth token against the API response: %s. Leaving state.auth_token_yaml unchanged.", err),
			)
			return
		}
		if !equivalent {
			tflog.Debug(ctx, "Auth token has changed, updating state")
			state.AuthTokenYaml = types.StringValue(apiResponseJSON)
		}
	} else {
		state.AuthTokenYaml = types.StringValue(apiResponseJSON)
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *AuthTokenResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var state, plan authTokenModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	body, err := converter.ConvertYAMLToJSON(plan.AuthTokenYaml.ValueString())
	if err != nil {
		resp.Diagnostics.AddError("Conversion Error", fmt.Sprintf("Unable to convert auth token YAML to JSON: %s", err))
		return
	}

	// The id, origin and secret are immutable across updates.
	plan.ID = state.ID
	plan.Origin = state.Origin
	plan.Token = state.Token
	if err := r.client.UpdateAuthToken(ctx, plan.ID.ValueString(), plan.Origin.ValueString(), body); err != nil {
		resp.Diagnostics.AddError("Client Error", fmt.Sprintf("Unable to update auth token, got error: %s", err))
		return
	}

	tflog.Trace(ctx, "updated an auth token resource")
	resp.Diagnostics.Append(resp.State.Set(ctx, plan)...)
}

func (r *AuthTokenResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state authTokenModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	if err := r.client.DeleteAuthToken(ctx, state.ID.ValueString()); err != nil {
		if dash0.IsNotFound(err) {
			tflog.Debug(ctx, fmt.Sprintf("Auth token %s was already gone at delete time; treating as success", state.ID.ValueString()))
			return
		}
		// The API refuses to delete the last auth token of the organization; its message says so.
		resp.Diagnostics.AddError("Client Error", fmt.Sprintf("Unable to delete auth token, got error: %s", err))
		return
	}

	tflog.Trace(ctx, "deleted an auth token resource")
}

// ImportState imports an existing auth token by its id or origin.
func (r *AuthTokenResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	apiResponseJSON, token, err := r.client.GetAuthToken(ctx, req.ID)
	if err != nil {
		resp.Diagnostics.AddError("Error Importing Auth Token", fmt.Sprintf("Could not get auth token %s: %s", req.ID, err))
		return
	}

	var id, origin string
	var parsed struct {
		Metadata struct {
			Labels map[string]interface{} `yaml:"labels"`
		} `yaml:"metadata"`
	}
	if yaml.Unmarshal([]byte(apiResponseJSON), &parsed) == nil {
		id, _ = parsed.Metadata.Labels[authTokenIDLabel].(string)
		origin, _ = parsed.Metadata.Labels[authTokenOriginKey].(string)
	}
	if id == "" {
		resp.Diagnostics.AddError("Error Importing Auth Token", fmt.Sprintf("The API response for auth token %s has no dash0.com/id label.", req.ID))
		return
	}

	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("id"), id)...)
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("origin"), stringOrNull(origin))...)
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("token"), stringOrNull(token))...)
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("auth_token_yaml"), apiResponseJSON)...)
}
